CREATE TABLE IF NOT EXISTS users (
 id CHAR(36) PRIMARY KEY, username VARCHAR(32) NOT NULL UNIQUE,
 password_hash VARCHAR(200) NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS sessions (
 token_hash CHAR(64) PRIMARY KEY, user_id CHAR(36) NOT NULL,
 expires_at DATETIME NOT NULL, FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS communities (
 id CHAR(36) PRIMARY KEY, name VARCHAR(80) NOT NULL, owner_id CHAR(36) NOT NULL,
 invite CHAR(48) NOT NULL UNIQUE, FOREIGN KEY (owner_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS members (
 community_id CHAR(36) NOT NULL, user_id CHAR(36) NOT NULL,
 PRIMARY KEY(community_id,user_id), FOREIGN KEY(community_id) REFERENCES communities(id) ON DELETE CASCADE,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS channels (
 id CHAR(36) PRIMARY KEY, community_id CHAR(36) NOT NULL, name VARCHAR(40) NOT NULL,
 FOREIGN KEY(community_id) REFERENCES communities(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS messages (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, channel_id CHAR(36) NOT NULL,
 user_id CHAR(36) NOT NULL, ciphertext TEXT NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 INDEX(channel_id,id), FOREIGN KEY(channel_id) REFERENCES channels(id) ON DELETE CASCADE,
 FOREIGN KEY(user_id) REFERENCES users(id)
);
